-- Run this in the Supabase SQL Editor for a new project.
-- Existing production tables should be reviewed before applying this schema.

create table if not exists public."Posts" (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) default auth.uid(),
  writer_name text not null,
  wirter_thumbnail text,
  title text not null,
  text text not null,
  created_at timestamptz not null default now(),
  thumbnail text
);

-- `CREATE TABLE IF NOT EXISTS` does not add new columns to an existing table.
-- Keep this nullable so existing posts without an authenticated owner are preserved.
alter table public."Posts"
  add column if not exists user_id uuid references auth.users (id) default auth.uid();

create index if not exists posts_created_at_idx
  on public."Posts" (created_at desc);

alter table public."Posts" enable row level security;

revoke all on table public."Posts" from anon, authenticated;
grant select on table public."Posts" to anon, authenticated;
grant insert, update, delete on table public."Posts" to authenticated;

drop policy if exists "Anyone can read posts" on public."Posts";
drop policy if exists "Authenticated users can create posts" on public."Posts";
drop policy if exists "Users can edit their own posts" on public."Posts";
drop policy if exists "Users can delete their own posts" on public."Posts";

create policy "Anyone can read posts"
  on public."Posts"
  for select
  to anon, authenticated
  using (true);

create policy "Authenticated users can create posts"
  on public."Posts"
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

create policy "Users can edit their own posts"
  on public."Posts"
  for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "Users can delete their own posts"
  on public."Posts"
  for delete
  to authenticated
  using ((select auth.uid()) = user_id);

insert into storage.buckets (id, name, public)
values ('post-images', 'post-images', true)
on conflict (id) do nothing;

drop policy if exists "Users can read their own post image metadata" on storage.objects;
drop policy if exists "Authenticated users can upload post images" on storage.objects;
drop policy if exists "Users can replace their own post images" on storage.objects;
drop policy if exists "Users can delete their own post images" on storage.objects;

-- Public URLs can serve images from this bucket without permitting object listings.
-- This narrow SELECT policy is required only for an authenticated user's upsert.
create policy "Users can read their own post image metadata"
  on storage.objects
  for select
  to authenticated
  using (
    bucket_id = 'post-images'
    and owner_id = (select auth.uid()::text)
  );

create policy "Authenticated users can upload post images"
  on storage.objects
  for insert
  to authenticated
  with check (
    bucket_id = 'post-images'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );

create policy "Users can replace their own post images"
  on storage.objects
  for update
  to authenticated
  using (
    bucket_id = 'post-images'
    and owner_id = (select auth.uid()::text)
  )
  with check (
    bucket_id = 'post-images'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );

create policy "Users can delete their own post images"
  on storage.objects
  for delete
  to authenticated
  using (
    bucket_id = 'post-images'
    and owner_id = (select auth.uid()::text)
  );
